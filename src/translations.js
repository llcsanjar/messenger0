// Забони пешфарз
const DEFAULT_LANG = 'ru';

// Гирифтани забони аз localStorage
export const getSavedLanguage = () => {
  return localStorage.getItem('app_language') || DEFAULT_LANG;
};

// Нигоҳдории забон дар localStorage
export const saveLanguage = (lang) => {
  localStorage.setItem('app_language', lang);
};

// Гирифтани translation барои забон
export const getTranslation = (lang) => {
  return translations[lang] || translations[DEFAULT_LANG];
};

// Функсияи тарҷумаи матнҳои динамикӣ
export const translate = (lang, key, params = {}) => {
  const t = getTranslation(lang);
  let text = t[key] || key;
  
  // Иваз кардани параметрҳо
  Object.keys(params).forEach(param => {
    text = text.replace(`{${param}}`, params[param]);
  });
  
  return text;
};

// Функсияи гирифтани забони браузер
export const getBrowserLanguage = () => {
  const browserLang = navigator.language || navigator.userLanguage;
  
  if (browserLang.startsWith('tg')) return 'tg';
  if (browserLang.startsWith('ru')) return 'ru';
  if (browserLang.startsWith('en')) return 'en';
  if (browserLang.startsWith('fa')) return 'fa';
  
  return DEFAULT_LANG;
};

// Функсияи оғозкунии забон дар аввали бори аввал
export const initLanguage = () => {
  let savedLang = getSavedLanguage();
  
  // Санҷидани дурустии забони сабтшуда
  const validLangs = ['tg', 'ru', 'en', 'fa'];
  if (!savedLang || !validLangs.includes(savedLang)) {
    savedLang = getBrowserLanguage();
    saveLanguage(savedLang);
  }
  
  // Тағйир додани direction барои RTL
  if (savedLang === 'fa') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.documentElement.style.direction = 'rtl';
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.style.direction = 'ltr';
  }
  
  return savedLang;
};

export default translations;